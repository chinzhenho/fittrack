const opt = (v: number | null) => (v === null || v < 0 ? undefined : v);

function toFood(r: Raw): Food {
  const [
    dishClass,
    crId,
    name,
    description,
    ,
    weight,
    edible,
    source,
    year,
    kcal,
    protein,
    fat,
    carbs,
    fibre,
    sugar,
    sodium,
  ] = r;
  const zh = ZH[crId];
  if (!zh) throw new Error(`missing display name for ${crId}`);
  const fiberG = opt(fibre);
  const sugarG = opt(sugar);
  const sodiumMg = opt(sodium);
  // Serving grams = edible part of the default serving (SG FoodID reports serving weight
  // including bones etc.), so per-serving energy matches SG FoodID's own per-serving figure.
  const ediblePerServing = Math.round(weight * edible) / 100;
  return {
    id: `sg-${crId}`,
    name: zh.name,
    nameEn: name,
    aliases: [...zh.aliases, name],
    per100g: {
      kcal,
      proteinG: protein,
      carbsG: carbs,
      fatG: fat,
      ...(fiberG !== undefined && { fiberG }),
      ...(sugarG !== undefined && { sugarG }),
      ...(sodiumMg !== undefined && { sodiumMg }),
    },
    source: 'sgfoodid',
    sourceRef: `SG FoodID ${crId} (${source === 'Lab Analysis' ? 'lab analysis' : 'calculated'}, ${year})`,
    description,
    servings: [{ label: `1 ${zh.unit}`, grams: ediblePerServing }],
    dishClass,
  };
}

export const SG_FOODS: Food[] = RAW.map(toFood);
